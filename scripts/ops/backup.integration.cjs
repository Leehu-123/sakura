const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const { randomUUID, createHash } = require('node:crypto');
const { Client } = require('pg');
const { config, createBackup, verifyBundle, drill } = require('./backup.cjs');
test('Snapshot PostgreSQL, ảnh, phục hồi dữ liệu chính xác và không đụng database nguồn', async () => {
  const source = config(),
    name = 'sakura_backup_test_' + randomUUID().replaceAll('-', '');
  const directory = path.join(source.backupRoot, 'tests', name);
  const admin = new Client({ ...source.connection, database: 'postgres' });
  let db,
    created = false;
  try {
    await admin.connect();
    await admin.query('CREATE DATABASE "' + name + '" TEMPLATE template0');
    created = true;
    db = new Client({ ...source.connection, database: name });
    await db.connect();
    await db.query(
      'CREATE TABLE public."Probe" (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, amount numeric(30,0), moment timestamptz, payload jsonb)',
    );
    await db.query('CREATE TABLE public."ProductImage" ("storageKey" text, "byteSize" integer)');
    await db.query('INSERT INTO public."Probe" (amount,moment,payload) VALUES ($1,$2,$3)', [
      '123456789012345678901234567890',
      '2025-06-01T12:34:56.123456+07:00',
      '{"test":"không mất độ chính xác"}',
    ]);
    const image = Buffer.from('image bytes in isolated backup test'),
      key = createHash('sha256').update(image).digest('hex');
    const mediaRoot = path.join(directory, 'source-media');
    await fs.mkdir(path.join(mediaRoot, key.slice(0, 2)), { recursive: true });
    await fs.writeFile(path.join(mediaRoot, key.slice(0, 2), key), image);
    await db.query('INSERT INTO public."ProductImage" VALUES ($1,$2)', [key, image.length]);
    await db.query('CREATE TABLE public."ChatAttachment" ("storageKey" text, "byteSize" integer)');
    const attachment = Buffer.from('document bytes in isolated chat backup test'),
      attachmentKey = createHash('sha256').update(attachment).digest('hex');
    await fs.mkdir(path.join(mediaRoot, attachmentKey.slice(0, 2)), { recursive: true });
    await fs.writeFile(path.join(mediaRoot, attachmentKey.slice(0, 2), attachmentKey), attachment);
    await db.query('INSERT INTO public."ChatAttachment" VALUES ($1,$2),($3,$4)', [
      attachmentKey,
      attachment.length,
      key,
      image.length,
    ]);
    const c = {
      ...source,
      connection: { ...source.connection, database: name },
      backupRoot: path.join(directory, 'bundles'),
      mediaRoot,
      onSnapshot: async () => {
        // A committed write after the exported snapshot must not enter the backup.
        await db.query('INSERT INTO public."Probe" (amount) VALUES (42)');
      },
    };
    const avatar = Buffer.from('isolated avatar bytes'),
      avatarKey = createHash('sha256').update(avatar).digest('hex');
    await fs.mkdir(path.join(mediaRoot, avatarKey.slice(0, 2)), { recursive: true });
    await fs.writeFile(path.join(mediaRoot, avatarKey.slice(0, 2), avatarKey), avatar);
    await db.query('CREATE TABLE public."ChatConversation" ("avatarKey" text, "avatarBytes" integer)');
    await db.query('INSERT INTO public."ChatConversation" VALUES ($1,$2)', [avatarKey, avatar.length]);
    const backup = await createBackup(c),
      manifest = await verifyBundle(backup.folder);
    assert.equal(manifest.tables.find((t) => t.name === 'Probe').rows, 1);
    assert.equal(manifest.mediaFiles, 3);
    const result = await drill(c, backup.folder);
    assert.equal(result.rows, 5);
    assert.equal(result.mediaFiles, 3);
    assert.equal(result.counters[0].valid, true);
    assert.equal((await db.query('SELECT count(*)::int AS n FROM public."Probe"')).rows[0].n, 2);
    await fs.unlink(path.join(mediaRoot, key.slice(0, 2), key));
    await assert.rejects(() => createBackup({ ...c, onSnapshot: undefined }), /ENOENT/);
    const complete = [];
    for (const entry of await fs.readdir(c.backupRoot, { withFileTypes: true }))
      if (entry.isDirectory()) {
        if (await fs.stat(path.join(c.backupRoot, entry.name, 'COMPLETE.json')).catch(() => false))
          complete.push(entry.name);
      }
    assert.equal(complete.length, 1);
    console.log('Test bundle retained under .local/backups/tests; application data unchanged.');
  } finally {
    if (db) await db.end();
    if (created) {
      if (!/^sakura_backup_test_[a-f0-9]{32}$/.test(name)) throw Error('Invalid test database');
      await admin.query('DROP DATABASE "' + name + '"');
    }
    await admin.end();
  }
});
